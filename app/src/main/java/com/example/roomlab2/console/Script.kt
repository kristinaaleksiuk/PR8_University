package com.example.roomlab2.console

/**
 * Сценарий проверки. Id при каждом запуске одинаковые, т.к. Console.run
 * перед стартом очищает таблицы и сбрасывает счётчики автоинкремента.
 *
 * Формат (дата дд.мм.гггг, оценка 0..5, дробная часть через точку):
 *   add group <название>|<курс>
 *   add student <groupId>|<имя>|<дата рождения>|<оценка>
 *   addmany <группа>|<курс>|<имя:дата:оценка>,<имя:дата:оценка>   (одна транзакция)
 *   update group <id>|<название>|<курс>
 *   update student <id>|<имя>|<дата рождения>|<оценка>
 *   delete group|student <id>
 *   list groups | list students [минимальнаяОценка]
 *   find name <текст> | find namekt <текст> | find grade <минимальнаяОценка>
 *   stat | join | bench
 */
object Script {
    val commands = listOf(
        // --- добавление ---
        "add group ИС-21|2",                                               // group 1
        "add group ПИ-31|3",                                               // group 2
        "add group ИБ-11|1",                                               // group 3
        "add student 1|Иван Петров|15.03.2004|4.5",                        // student 1
        "add student 1|Мария Сидорова|02.11.2003|4.9",                     // student 2
        "add student 2|Алексей Смирнов|21.07.2002|3.8",                    // student 3
        "add student 3|Ольга Кузнецова|09.01.2005|4.2",                    // student 4
        // --- транзакция: группа + 3 студента ---
        "addmany ИТ-41|4|Дмитрий Орлов:30.05.2001:4.7,Анна Волкова:12.12.2001:3.5,Сергей Лебедев:08.08.2001:4.1",
        // --- вывод (способ 1: filter / map / sortedBy) ---
        "list groups",
        "list students",
        "list students 4.0",
        // --- выборки (способ 2: @Query) ---
        "find name Иван",
        "find grade 4.5",                                                  // оценка не ниже, по убыванию
        "stat",
        "join",
        // --- изменение и удаление ---
        "update student 3|Алексей Смирнов|21.07.2002|4.4",
        "update group 3|ИБ-11 (бакалавриат)|1",
        "find grade 4.0",
        "delete student 6",
        "delete group 2",                                                  // каскадно удалит его студентов
        "join",
        // --- ошибочные команды ---
        "add group |2",                                                    // пустое название
        "add student 99|Призрак|01.01.2000|4.0",                           // нет группы -> FOREIGN KEY
        "update student 999|Икс|01.01.2000|4.0",                           // нет такого id
        "delete group 999",                                                // нет такого id
        "add student 1|Тест|32.13.2000|4.0",                               // неверная дата
        "add student 1|Тест|01.01.2000|7.5",                               // оценка вне диапазона
        "add student 1|Тест|01.01.2000|abc",                               // не число
        "addmany ТЕСТ-1|1|Хороший:01.01.2000:4.0,Плохой:01.01.2000:9.0",   // откат транзакции
        "list groups",                                                     // «ТЕСТ-1» не должна появиться
        "foo bar",                                                         // неизвестная команда
        // --- сравнение способов на 1500 записях ---
        "bench",
        "stat"
    )
}
